import { mkdir, copyFile } from "node:fs/promises";
import { join } from "node:path";
const root=process.cwd();
const sans=join(root,"node_modules","geist","dist","fonts","geist-sans");
const mono=join(root,"node_modules","geist","dist","fonts","geist-mono");
const target=join(root,"public","fonts");
await mkdir(target,{recursive:true});
await copyFile(join(sans,"Geist-Regular.ttf"),join(target,"Geist-Regular.ttf"));
await copyFile(join(sans,"Geist-SemiBold.ttf"),join(target,"Geist-SemiBold.ttf"));
await copyFile(join(mono,"GeistMono-Regular.ttf"),join(target,"GeistMono-Regular.ttf"));
console.log("Prepared Geist Sans Regular/SemiBold and Geist Mono Regular.");
