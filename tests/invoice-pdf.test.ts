import test from "node:test";
import assert from "node:assert/strict";
import {PDFDocument} from "pdf-lib";
import {renderInvoicePdf} from "../lib/ledger/invoice-pdf";
import type {TrackerRow,InvoiceGroup} from "../lib/tracker";
function fixture(count=3):InvoiceGroup{
 const rows=Array.from({length:count},(_,i)=>({
  id:"row-"+i,project_name:"Design and development service "+(i+1)+" of a much longer descriptive statement",
  amount:1200,quantity:2,unit_price:600,assigned_by:null,row_order:i+1,invoice_number:"INV-122"
 })) as unknown as TrackerRow[];
 return {number:"INV-122",rows,total:count*1200+216,paid:0,balance:count*1200+216,
  lineTotal:count*1200,taxRate:count===3?6:0,taxAmount:count===3?216:0,
  date:"2026-11-08",dueDate:"2026-11-22",sourceStatus:"Draft",sourceSettled:false,sourcePaidOn:null,
  recordedPayments:0,discrepancy:count===3?0:-216,publicNotes:"Delivery notes",
  paymentState:"Unpaid",document:null};
}
test("renders a valid multi-organisation invoice without relying on live credentials",async()=>{
 const bytes=await renderInvoicePdf({organization:{name:"The Minimical Co.",address:"India",bank_name:"Example Bank"},client:{name:"A new client",email:"example@client.invalid"},invoice:fixture()});
 assert.equal(Buffer.from(bytes.subarray(0,5)).toString(),"%PDF-");
 const pdf=await PDFDocument.load(bytes);
 assert.equal(pdf.getTitle(),"Invoice INV-122 - The Minimical Co.");
 assert.equal(pdf.getPageCount(),1);
});
test("paginates invoices with many work items and keeps all pages valid",async()=>{
 const bytes=await renderInvoicePdf({organization:{name:"Kumar Aman",invoice_footer:"Generated by the finance workspace"},client:{name:"Elle India"},invoice:fixture(54)});
 const pdf=await PDFDocument.load(bytes);
 assert.ok(pdf.getPageCount()>1);
 assert.ok(pdf.getPageCount()<15);
});
test("handles long invoice details and empty optional fields",async()=>{
 const bytes=await renderInvoicePdf({organization:{name:"Long Organisation ".repeat(12),address:"A".repeat(400)},client:null,
  invoice:{...fixture(1),publicNotes:"This message is a long note ".repeat(150),taxAmount:0,discrepancy:0,total:1200,balance:1200}});
 const doc=await PDFDocument.load(bytes);
 assert.ok(doc.getPageCount()>=2);
});
